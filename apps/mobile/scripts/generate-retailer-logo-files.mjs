#!/usr/bin/env node
/**
 * Writes `src/features/loyalty-cards/components/retailer-logo-files.ts`: one
 * `require` per shipped Retailer logo, so Metro bundles the files and an
 * over-the-air update carries them (APP-159). Metro only bundles a file it
 * sees required by a literal path, so the list cannot be built at run time.
 *
 * Run it after `scripts/prepare-retailer-logos.mjs` adds or removes a logo:
 *
 *   node apps/mobile/scripts/generate-retailer-logo-files.mjs
 *
 * `scripts/mobile-retailer-logo-files.test.ts` fails while the committed file
 * is stale.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  RETAILER_LOGOS,
  retailerLogoFileName,
} from '../../../packages/core/src/retailerLogos.ts'

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

export const OUTPUT = path.join(
  mobileRoot,
  'src/features/loyalty-cards/components/retailer-logo-files.ts',
)

/**
 * The phone bundles only the 192 px file: its largest tile is 56 pt, which
 * needs 168 px on a 3x screen, and one size keeps the update small.
 */
export const PHONE_LOGO_SIZE = 192

const FROM_OUTPUT_TO_LOGOS = '../../../../../../packages/core/assets/retailer-logos/'

/** The file's text for the given logo keys. */
export function renderRetailerLogoFiles(keys = Object.keys(RETAILER_LOGOS)) {
  const lines = [...keys]
    .sort()
    .map(
      (key) =>
        `  '${key}': require('${FROM_OUTPUT_TO_LOGOS}${retailerLogoFileName(key, PHONE_LOGO_SIZE)}'),`,
    )
  return [
    '// Generated by apps/mobile/scripts/generate-retailer-logo-files.mjs from',
    '// RETAILER_LOGOS in @gather/core/retailer-logos. Do not edit by hand.',
    '',
    '/** Each shipped logo, as the asset Metro bundles, by Catalog `seedKey`. */',
    'export const RETAILER_LOGO_FILES: Readonly<Record<string, number>> = {',
    ...lines,
    '}',
    '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUTPUT, renderRetailerLogoFiles())
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`)
}
