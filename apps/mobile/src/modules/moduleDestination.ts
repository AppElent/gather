/**
 * Where a Module's screens are, and the one place their addresses are built.
 *
 * Modules live once, inside the All tab's stack (ADR-0023). Most have no native
 * workflow yet and land on `ModulePlaceholder` via the dynamic `[moduleId]`
 * route. The ones that are built have real screens at a static segment —
 * `/all/baby-log` — and a static route must be named explicitly: navigating to
 * `{pathname: '/all/[moduleId]', params: {moduleId: 'baby-log'}}` targets the
 * dynamic route, which would render the placeholder over a Module that exists.
 *
 * `moduleDestination` is the single answer to "open this Module": All's rows,
 * the dynamic route (`shell/ModuleRoute.tsx`) and the `/g/<slug>` handoff
 * (`shell/groupLink.ts`) all ask it. **When a Module gets its native screens,
 * add it to `NATIVE_MODULES`** — `moduleDestination.test.ts` then checks that
 * the address it answers is a real route file.
 */
import type { ModuleId } from '@gather/core/modules'
import { type TastingKind, tastingKindForModule } from '@gather/core/tastings'
import type { Href } from 'expo-router'

/** Modules with real screens in the phone's route tree. */
export const NATIVE_MODULES = [
  'baby-log',
  'recipes',
  'cheeses',
  'wines',
  'beers',
  'tasks',
  'notes',
  'meal-planner',
  'groceries',
  'pantry',
  'calendar',
  'recurring-costs',
  'shared-costs',
  'savings-goals',
] as const satisfies readonly ModuleId[]

export type NativeModuleId = (typeof NATIVE_MODULES)[number]

export function isNativeModule(id: string): id is NativeModuleId {
  return (NATIVE_MODULES as readonly string[]).includes(id)
}

/**
 * Where opening a Module goes: its own screens, or the placeholder.
 *
 * A plain string rather than `ModuleId`: callers hold a `ModuleDef`'s `id`,
 * which the catalogue types loosely, and an unknown id simply lands on the
 * placeholder route, which redirects it to All.
 */
export function moduleDestination(moduleId: string): Href {
  // The three tasting Modules are one implementation behind a `[kind]`
  // segment, so their segment is the Kind rather than the Module id — the one
  // place a Module's route is not named after it.
  const kind = tastingKindForModule(moduleId)
  if (kind) return moduleHref(`/all/tasting/${kind}`)
  if (isNativeModule(moduleId)) return moduleHref(`/all/${moduleId}`)
  return { pathname: '/all/[moduleId]', params: { moduleId } }
}

/**
 * Every address below a Module's index that a screen pushes to by name.
 *
 * Listed rather than `string` so a renamed screen is a type error at every
 * caller. A screen a Module adds goes here with its route file.
 */
export type ModulePath =
  | `/all/${NativeModuleId}`
  | `/all/baby-log${'' | '/new' | '/settings' | '/timeline' | '/trends' | '/lists' | '/entry'}`
  | `/all/recipes${'' | '/recipe' | '/import' | '/new' | '/edit'}`
  | `/all/tasting/${TastingKind}${'' | '/subject' | '/compose'}`
  | `/all/recurring-costs${'' | '/cost'}`
  | `/all/savings-goals${'' | '/goal'}`
  | `/settings/labs/finance${
      | ''
      | '/house'
      | '/mortgage'
      | '/part'
      | '/timeline'
      | '/buying-costs'
      | '/portfolio'
      | '/holding'
      | '/net-worth'}`

/**
 * The href for a Module screen, with its params.
 *
 * The cast lives here alone: typed routes are generated by Metro rather than
 * by `tsc`, so a literal path can fail the typecheck on a route that is real.
 * `ModulePath` is the check this function keeps instead.
 */
export function moduleHref(
  path: ModulePath,
  params?: Record<string, string>,
): Href {
  return (params ? { pathname: path, params } : path) as Href
}
