// The readable grocery names the composer completes from (APP-311): the
// hand-written terms of curated.txt as they are written, one per
// `groceryKey`, per aisle. The bundled dictionary keeps only stems ("kaas"
// is "kas" there), which are fine for finding an aisle but not to show.
//
// `build-names.ts` writes them to
// packages/core/src/groceries/data/names.generated.ts, and
// scripts/grocery-names.test.ts fails when that file and curated.txt differ.
import {
  GROCERY_AISLES,
  type GroceryAisle,
  isGroceryAisle,
} from '../../packages/core/src/groceries/aisles'
import { groceryKey } from '../../packages/core/src/groceries/normalise'

/** Per aisle, its names joined by `|`, in curated.txt's order. */
export type GroceryNamesData = Partial<Record<GroceryAisle, string>>

/** The names of curated.txt's `aisle: term, …` lines; `drop:` is skipped. */
export function curatedNames(text: string): GroceryNamesData {
  const seen = new Set<string>()
  const byAisle = new Map<GroceryAisle, string[]>()
  for (const raw of text.split('\n')) {
    const line = raw.replace(/#.*/, '').trim()
    if (!line || line.startsWith('drop:')) continue
    const colon = line.indexOf(':')
    const aisle = line.slice(0, colon).trim()
    if (colon < 0 || !isGroceryAisle(aisle)) continue
    for (const term of line.slice(colon + 1).split(',')) {
      const name = term.trim().replace(/\|/g, '')
      const key = groceryKey(name)
      if (!key || seen.has(key)) continue
      seen.add(key)
      const names = byAisle.get(aisle) ?? []
      names.push(name)
      byAisle.set(aisle, names)
    }
  }
  const data: GroceryNamesData = {}
  for (const aisle of GROCERY_AISLES) {
    const names = byAisle.get(aisle)
    if (names) data[aisle] = names.join('|')
  }
  return data
}

/** The generated module's source. */
export function namesModule(data: GroceryNamesData): string {
  return [
    '/**',
    ' * GENERATED by scripts/groceries/build-names.ts from',
    ' * scripts/groceries/curated.txt; do not edit by hand. The names the',
    ' * grocery composer completes from (APP-311), per aisle, joined by `|`.',
    ' */',
    "import type { GroceryNamesData } from '../completions'",
    '',
    'export const GROCERY_NAMES_DATA: GroceryNamesData = {',
    ...Object.entries(data).map(
      ([aisle, names]) =>
        `  ${aisle}:\n    '${names.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`,
    ),
    '}',
    '',
  ].join('\n')
}
