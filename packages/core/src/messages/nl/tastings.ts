/**
 * Dutch for the tasting Modules.
 *
 * Two rules from ADR-0011's glossary do the work here. **Proeverij** is one
 * person's tasting of one thing — the record — and never the act of tasting in
 * general. And a **subject's own name is content**: Comté stays Comté, and so
 * does a household's Boerenkaas Remeker (story 30). Only the chrome is Dutch.
 *
 * Where a term is a proper noun the two locales are identical on purpose —
 * Nebbiolo, Marlborough, IPA. That is not duplication to collapse: it is where
 * the Dutch word would go the day one exists, and `Bourgogne` already proves
 * the day comes.
 */

